"""
accuracy.py -- CLAUDE.md section 6.2: run labelled trials against the LIVE
firmware (empty / sitting / walking, with fan on/off), print accuracy and a
confusion matrix, and save to docs/accuracy.md.

This project's presence classification is decided by the ESP32 firmware
itself (not a separate Python classifier -- the original brief imagined
training one from raw CSI features in /brain, but the firmware already
computes presence on-device and writes it straight to Firebase). So this
script tests the REAL end-to-end system: you physically set up a labelled
situation in the room, this script reads whatever /room1/state says at that
moment, and compares.

This can only be run with the real ESP32 + sensors in the room -- there is
no way to produce real accuracy numbers without that. Running it is on the
list in docs/progress.md; this script is what docs/accuracy.md's template
tells you to run.

Usage:
    python accuracy.py                  # 20 trials (CLAUDE.md's minimum)
    python accuracy.py --trials 30
"""
import argparse
import json
import time
from datetime import datetime
from pathlib import Path

from firebase_admin import db

from firebase_db import get_app

BRAIN_DIR = Path(__file__).parent
DOCS_DIR = BRAIN_DIR.parent / "docs"

LABELS = ["empty", "sitting", "walking"]
FAN_STATES = [False, True]


def read_live_state(room: str = "room1") -> dict:
    get_app()
    return db.reference(f"/{room}/state").get() or {}


def run_trial(expected_presence: str, expected_fan_on: bool, settle_seconds: int) -> dict:
    print(f"\n--- Set up: presence = {expected_presence.upper()}, fan = {'ON' if expected_fan_on else 'OFF'} ---")
    input(f"Get the room into this state, then press Enter (will wait {settle_seconds}s to settle)...")
    time.sleep(settle_seconds)
    state = read_live_state()
    actual_presence = state.get("presence", "unsure")
    actual_fan_on = bool(state.get("fan_on", False))
    correct = actual_presence == expected_presence
    print(f"  -> firmware says presence={actual_presence}, fan_on={actual_fan_on} -- {'CORRECT' if correct else 'WRONG'}")
    return {
        "ts": int(time.time() * 1000),
        "expected_presence": expected_presence,
        "expected_fan_on": expected_fan_on,
        "actual_presence": actual_presence,
        "actual_fan_on": actual_fan_on,
        "presence_correct": correct,
        "fan_correct": actual_fan_on == expected_fan_on,
    }


def confusion_matrix(trials: list) -> dict:
    matrix = {a: {p: 0 for p in LABELS + ["unsure"]} for a in LABELS}
    for t in trials:
        expected = t["expected_presence"]
        actual = t["actual_presence"] if t["actual_presence"] in matrix[expected] else "unsure"
        matrix[expected][actual] += 1
    return matrix


def write_report(trials: list):
    total = len(trials)
    presence_correct = sum(1 for t in trials if t["presence_correct"])
    fan_correct = sum(1 for t in trials if t["fan_correct"])
    matrix = confusion_matrix(trials)

    lines = [
        "# Accuracy",
        "",
        f"Generated by `brain/accuracy.py` on {datetime.now().strftime('%Y-%m-%d %H:%M')}, "
        f"from {total} real labelled trials against the live ESP32 + Firebase (not simulated).",
        "",
        f"- **Presence accuracy:** {presence_correct}/{total} ({presence_correct / total * 100:.0f}%)",
        f"- **Fan on/off accuracy:** {fan_correct}/{total} ({fan_correct / total * 100:.0f}%)",
        "",
        "## Confusion matrix (presence)",
        "",
        "Rows = what the room was actually set up as. Columns = what the firmware reported.",
        "",
        "| actual \\\\ reported | " + " | ".join(LABELS + ["unsure"]) + " |",
        "|---" * (len(LABELS) + 2) + "|",
    ]
    for expected in LABELS:
        row = [str(matrix[expected][p]) for p in LABELS + ["unsure"]]
        lines.append(f"| {expected} | " + " | ".join(row) + " |")

    lines += [
        "",
        "## Known caveat",
        "",
        "`light_on`/`fan_on` sometimes read false even when physically on (a firmware/sensor "
        "calibration issue noted in docs/progress.md, not fixed by instruction -- the app displays "
        "whatever the firmware reports, correctly). A low fan accuracy number here most likely "
        "reflects that, not the presence model.",
    ]

    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "accuracy.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {DOCS_DIR / 'accuracy.md'}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run labelled presence-accuracy trials against the live firmware.")
    parser.add_argument("--trials", type=int, default=20, help="Total trials to run (CLAUDE.md asks for at least 20).")
    parser.add_argument("--settle-seconds", type=int, default=15, help="Seconds to wait after setup before reading the firmware's state.")
    args = parser.parse_args()

    print(f"Running {args.trials} trials. For each one, physically set up the room, then press Enter.")
    combos = [(label, fan) for label in LABELS for fan in FAN_STATES]
    results = []
    for i in range(args.trials):
        label, fan = combos[i % len(combos)]
        results.append(run_trial(label, fan, args.settle_seconds))

    write_report(results)
    raw_path = DOCS_DIR / "accuracy_trials_raw.json"
    raw_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"Raw trial data saved to {raw_path}")
